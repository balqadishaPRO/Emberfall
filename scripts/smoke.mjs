import { readFileSync } from 'node:fs';
import { runInThisContext } from 'node:vm';
import assert from 'node:assert/strict';
runInThisContext(readFileSync('dist/wasm_exec.js', 'utf8'));
const go = new Go();
const { instance } = await WebAssembly.instantiate(readFileSync('dist/game.wasm'), go.importObject);
go.run(instance);
let state = JSON.parse(gamatNew('42', 'normal'));
assert.equal(state.nodes.length, 9);
assert.equal(gamatSend(1, 0, .5), false);
assert.equal(gamatUpgrade(0), true);
assert.equal(JSON.parse(gamatStep(0)).nodes[0].level, 2);
assert.equal(gamatSend(0, 3, 1), true);
for (let i = 0; i < 6100; i++) state = JSON.parse(gamatStep(.05));
assert.ok(['victory', 'defeat', 'draw'].includes(state.status));
assert.ok(state.nodes.every(n => Number.isFinite(n.units) && n.units >= 0));
assert.ok(state.time <= 300);
console.log(`Go/WASM smoke passed: full match, orders, upgrades, valid state (${state.status}).`);
process.exit(0);
